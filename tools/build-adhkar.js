const fs = require('fs'), path = require('path');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'hisn-27.json'), 'utf8').replace(/^﻿/, ''));
const items = Object.fromEntries(Object.values(src)[0].map(x => [x.ID, x]));

// نصّ الذكر: بين (( و )) فقط، بلا عدد المرات ولا ملاحظة المساء، ومسافات موحّدة
// ترتيب الحركات: الشدّة قبل الحركة (المصدر يخلط بين الترتيبين)
const ord = t => t.replace(/([ً-ِْ])ّ/g, 'ّ$1');
function body(id){
  const t = items[id].ARABIC_TEXT, a = t.indexOf('(('), b = t.indexOf('))');
  if (a < 0 || b < 0) throw new Error('لا نصّ بين الأقواس: ' + id);
  return ord(t.slice(a + 2, b)).replace(/ـ/g, '').replace(/\s*:\s*/g, ': ').replace(/\s+،/g, '،').replace(/\s+/g, ' ').trim();
}
function swap(t, pairs, id){
  pairs.map(([a, b]) => [ord(a), ord(b)]).forEach(([a, b]) => { if (!t.includes(a)) throw new Error(`الذكر ${id}: لم يوجد «${a}»`); t = t.split(a).join(b); });
  return t;
}
